    src = {"path": up["path"], "lines": rm_lines}
    obj_cols = [i for i in range(4, 18) if i in moving]
    goal_cols = [i for i in (36, 37, 38) if i in moving]
    hand_cols = [i for i in range(0, 4) if i in moving]
