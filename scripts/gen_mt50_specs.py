class _Dumper(yaml.SafeDumper):
    """No `&id001`/`*id001` aliases: a `source` mapping cited by three entries is three
    citations, and a reader (or `grep`) should see each in place."""

    def ignore_aliases(self, data: Any) -> bool:  # noqa: D401
        return True


def _dump(doc: Dict[str, Any], mw_version: str) -> str:
    body = yaml.dump(doc, Dumper=_Dumper, sort_keys=False, width=100, allow_unicode=True,
                     default_flow_style=False)
    return HEADER.format(mw=mw_version) + body


def _ensure_stubs(template: Dict[str, Any]) -> List[str]:
    """Break the bootstrap cycle. `bird.envs.metaworld` (which owns the observation table
    this script copies) refuses to import unless the catalogue holds exactly the fifty
    Meta-World specs, so on a tree where some of the forty do not exist yet a template
    copy with only `id`/`env_id` changed is written first and overwritten below."""
    made = []
    for task, row in _AUTHORED.items():
        out = TASKS / row["id"] / "shared_spec.yaml"
        if not out.is_file():
            stub = copy.deepcopy(template)
            stub["id"] = row["id"]
            stub["env"]["env_id"] = task
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(yaml.safe_dump(stub, sort_keys=False, width=100, allow_unicode=True))
            made.append(row["id"])
    return made


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tasks", nargs="*", default=None,
                    help="spec ids (directory names) to (re)generate; default all forty")
    ap.add_argument("--check", action="store_true",
                    help="regenerate in memory and report which committed files differ")
    ap.add_argument("--skip-mt10", action="store_true",
                    help="do not touch the ten MT10 specs' flat_fields / entry.lines")
    args = ap.parse_args(argv)

    template = yaml.safe_load(TEMPLATE.read_text())
    if not args.check:
        stubs = _ensure_stubs(template)
        if stubs:
            print(f"bootstrap: wrote {len(stubs)} template stubs, overwritten below", file=sys.stderr)
    record = json.loads(ANCHORS_RECORD.read_text()) if ANCHORS_RECORD.is_file() else None
    if record is None:
        print(f"note: {ANCHORS_RECORD.relative_to(ROOT)} absent -- anchors written as null "
              "with a reason", file=sys.stderr)
    wanted = set(args.tasks or [r["id"] for r in _AUTHORED.values()])
    from importlib.metadata import version
    mw_version = version("metaworld")
    differ = []
    for task, row in _AUTHORED.items():
        if row["id"] not in wanted:
            continue
        doc = build(task, template, record)
        text = _dump(doc, mw_version)
        # The leak guard reads the spec WITHOUT `flat_fields`: that block is the adapter's
        # shared observation table, copied verbatim into all fifty and pinned to
        # `_STATE_FIELDS` by `test_flat_fields_is_the_adapters_observation_table`, and it
        # names the MT10 tasks whose quaternion is constant zeros -- window_open and
        # window_close among them. That is the table describing the ten, not the template
        # leaking; everything else in the dump is still held to the rule.
        probe = copy.deepcopy(doc)
        probe["state_surface"]["flat_fields"] = []
        probe_text = _dump(probe, mw_version).lower().replace("windows", "")
        assert "window" not in probe_text or task.startswith("window"), (
            f"{row['id']}: a window-specific string survived from the template")
        out = TASKS / row["id"] / "shared_spec.yaml"
        if args.check:
            if not out.is_file() or out.read_text() != text:
                differ.append(str(out.relative_to(ROOT)))
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text)
            print(f"wrote {out.relative_to(ROOT)}  ({len(doc['env']['reset']['draws'])} draws, "
                  f"{doc['state_surface']['fields'][3]['description'][:40]!r})")
    if not args.skip_mt10:
        changed = _patch_mt10(write=not args.check)
        if args.check:
            differ += changed
        elif changed:
            print("patched MT10 specs:", ", ".join(changed))
    if args.check:
        if differ:
            print("DIFFER:", *differ, sep="\n  ")
            return 1
        print("all generated specs are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
