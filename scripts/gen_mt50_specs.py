def _patch_mt10(write: bool) -> List[str]:
    """Bring the ten hand-authored specs' `flat_fields` to the adapter's shared table and
    their `entry.lines` to `MetaWorld._reset`'s current span. Text edits, so the files'
    comments survive; anything else in them is left alone."""
    from bird.tasks import METAWORLD_MT10
    from bird import tasks
    changed = []
    span = _reset_entry_lines()
    flat = _flat_fields()
    for spec in tasks.index().values():
        if spec.library != "metaworld" or spec.env_id not in METAWORLD_MT10:
            continue
        text = spec.path.read_text()
        new = text
        # entry.lines of MetaWorld._reset
        new = re.sub(r"(symbol: MetaWorld\._reset\n\s*lines: )[\d-]+", rf"\g<1>{span}", new)
        # flat_fields: rewrite the whole list in place, from `  flat_fields:` to `  helpers_note:`
        m = re.search(r"\n  flat_fields:\n(.*?)(?=\n  helpers_note:)", new, re.S)
        if m:
            dumped = yaml.safe_dump(flat, sort_keys=False, width=100, allow_unicode=True,
                                    default_flow_style=False)
            body = "".join("    " + line + "\n" for line in dumped.rstrip("\n").splitlines())
            new = new[:m.start()] + "\n  flat_fields:\n" + body.rstrip("\n") + new[m.end():]
        if new != text:
            changed.append(str(spec.path.relative_to(ROOT)))
            if write:
                spec.path.write_text(new)
    return changed


