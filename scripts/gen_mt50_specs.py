def _anchor(value: Optional[float], role: str, red: str, n: int, record_name: str,
            date_str: str) -> Dict[str, Any]:
    method = "random_policy" if role == "random" else "scripted_policy"
    if value is None:
        return {"value": None, "method": "unavailable", "source": None,
                "reason": (f"not yet measured: run `scripts/measure_anchors.py --tasks <id> --n 30` "
                           f"and re-run scripts/gen_mt50_specs.py; the generator reads "
                           f"{record_name}"),
                "n_seeds": None, "n_episodes": None, "date": None}
    what = ("fraction of n={n} {who} episodes in which the shipped success check held on at "
            "least one step" if red == "any_step_episode_fraction" else
            "mean `task_metric` -- the fraction of an episode's arriving states inside the "
            "goal region -- over n={n} {who} episodes through bird/envs/metaworld.py")
    who = ("uniform-random" if role == "random" else
           "scripted-expert (metaworld.policies.ENV_POLICY_MAP[task], the benchmark's own "
           "scripted solution and the honest ceiling here)")
    return {
        "value": round(float(value), 4), "method": method,
        "source": (f"MEASURED {date_str}: " + what.format(n=n, who=who) + ", seed 0. Taken from "
                   "the SAME rollouts as this task's other reduction, which is the only way the "
                   "pair can be guaranteed consistent (per-step <= any-step, always). The "
                   "scripted policy is handed a COPY of the observation: Meta-World's policies "
                   f"mutate it in place. Raw record: {record_name}."),
        "n_seeds": n, "n_episodes": n, "reason": None, "date": date_str,
    }


def _anchors_block(task_id: str, record: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    name = f"tasks/{ANCHORS_RECORD.name}"
    got = (record or {}).get("tasks", {}).get(task_id) if record else None
    n = int(record["n_episodes"]) if record else 0
    d = str(record["date"]) if record else ""

    def val(role, red):
        if not got or not got.get(role):
            return None
        return got[role][red]
    by = {red: {role: _anchor(val(role, red), role, red, n, name, d)
                for role in ("random", "expert")}
          for red in ("any_step_episode_fraction", "per_step_fraction")}
    return {
        "reduction": "any_step_episode_fraction",
        "by_reduction": by,
        "random": copy.deepcopy(by["any_step_episode_fraction"]["random"]),
        "expert": copy.deepcopy(by["any_step_episode_fraction"]["expert"]),
    }


