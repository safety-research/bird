#   expr        the check as one line, in upstream's own names
#   unsound     why the shipped check is loose (per-step, no settledness, ...)
#   distance    the `symbol_mapping.distance_to_goal` rhs (object-to-goal unless stated)
#   telemetry   `judge.telemetry_fields`
