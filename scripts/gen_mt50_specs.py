#!/usr/bin/env python3
"""Generate the forty MT50-only Meta-World task specs (`tasks/<id>/shared_spec.yaml`).

    uv sync --frozen --extra metaworld --extra test
    uv run --frozen python3 scripts/gen_mt50_specs.py                 # all forty
    uv run --frozen python3 scripts/gen_mt50_specs.py --tasks hammer   # one
    uv run --frozen python3 scripts/gen_mt50_specs.py --check          # regenerate and diff

WHAT IS AUTHORED AND WHAT IS MEASURED. The ten MT10 specs were written by hand, one
at a time, against the source. Forty more by hand would be forty chances to paste the
wrong line number, so this script splits each spec into three kinds of content and
says which is which on every field it can:

  * AUTHORED -- the prose (`_AUTHORED` below): what the task is, how the instruction
    reads, what the success check means and where it is loose, which telemetry the
    judge should see. Edit it HERE; the output files say so in their header.
  * READ from the installed `metaworld` wheel by `ast`/`inspect`: the file a task
    lives in and its sha256, the line spans of `reset_model`, `compute_reward` and
    `evaluate_state`, the line that assigns `"success"`, and the quaternion source
    (`Rotation.from_matrix(...)` -> scipy x,y,z,w order; `data.body(...).xquat` ->
    MuJoCo w,x,y,z). A citation the script read cannot have aged.
  * MEASURED on the live simulator, the way the adapter runs it (`MT1(task, seed=0)`,
    all fifty pinned instances, `set_task` + `reset()`): which observation columns
    move across instances and which do not, the range of each moving column, whether
    the goal is a rigid offset of the object draw (`derived`) or its own draw, and
    the hand's settled start. `env.reset` is built from that table and nothing else,
    which is what `tests/test_task_specs.py`'s reset-draw measurement holds it to.

The template is `tasks/window_open/shared_spec.yaml`, loaded and overridden field by
field rather than re-typed: the schema is `additionalProperties: false` throughout and
a hand-typed shape drifts from it in ways only the validator sees. Everything the
template carries that is Meta-World-wide (the 39-D observation table, the action
table, the DR axes, the reward contract, the forbidden-symbol lists, the shaping
primitives) is copied; everything task-specific is replaced; nothing window-specific
survives (the `--check` mode greps the output for "window" to prove it).

ANCHORS come from `tasks/_anchors_<date>.json`, the raw record `scripts/measure_anchors.py`
writes; the file to read is `ANCHORS_RECORD` below. The first pass, before the record
exists, writes every anchor as null WITH the reason, which is the schema's rule for a
value not yet obtained; once the record is measured, re-run and the values land.

Two things this script does NOT do. It does not decide the success-check
transcription -- that is Python in `bird/envs/metaworld.py`, resolved through the
closed allow-list, and the spec only NAMES it (`_AUTHORED[...]["symbol"]`). And it does
not touch the ten MT10 specs except for two mechanical edits it can prove are
mechanical: their `flat_fields` descriptions (which must equal the adapter's shared
table) and the `entry.lines` of `MetaWorld._reset` (which move when the adapter grows).
"""
