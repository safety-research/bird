def _reset_entry_lines() -> str:
    src = (ROOT / "bird" / "envs" / "metaworld.py").read_text()
    tree = ast.parse(src)
    for node in ast.walk(tree):
        if isinstance(node, ast.ClassDef) and node.name == "MetaWorld":
            for sub in node.body:
                if isinstance(sub, ast.FunctionDef) and sub.name == "_reset":
                    return f"{sub.lineno}-{sub.end_lineno}"
    raise LookupError("MetaWorld._reset")


_NAMES = None


def _names() -> List[str]:
    global _NAMES
    if _NAMES is None:
        from bird.envs.metaworld import _STATE_FIELDS
        _NAMES = [n for n, _ in _STATE_FIELDS]
    return _NAMES


def _fields_for(cols: List[int]) -> List[str]:
    names = _names()
    return [names[i] for i in cols] + [names[i + 18] for i in cols if i < 18]


def _fmt_range(lo: np.ndarray, hi: np.ndarray, cols: List[int]) -> str:
    names = _names()
    parts = []
    for i in cols:
        parts.append(f"{names[i]} in [{lo[i]:.4f}, {hi[i]:.4f}]")
    return "; ".join(parts)


