def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _span(src: str, name: str) -> Tuple[int, int]:
    tree = ast.parse(src)
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name == name:
            return int(node.lineno), int(node.end_lineno)
    raise LookupError(name)


def _line_of(src: str, pattern: str, lo: int, hi: int) -> Optional[int]:
    for i, line in enumerate(src.splitlines(), start=1):
        if lo <= i <= hi and re.search(pattern, line):
            return i
    return None


def _read_upstream(task: str) -> Dict[str, Any]:
    import metaworld
    from metaworld.env_dict import ALL_V3_ENVIRONMENTS

    cls = ALL_V3_ENVIRONMENTS[task]
    path = Path(inspect.getsourcefile(cls))
    src = path.read_text()
    rel = "metaworld/" + str(path).split("/metaworld/", 1)[1]
    pkg = Path(metaworld.__file__).parent
    quat_src = inspect.getsource(cls._get_quat_objects)
    if "Rotation.from_matrix" in quat_src or "as_quat" in quat_src:
        order = "scipy"
    elif "xquat" in quat_src:
        order = "mujoco"
    else:
        order = "zeros"
    ev = _span(src, "evaluate_state")
    return {
        "cls": cls.__name__, "path": rel, "sha256": _sha256(path),
        "reset_model": _span(src, "reset_model"),
        "compute_reward": _span(src, "compute_reward"),
        "evaluate_state": ev,
        "success_line": _line_of(src, r'"success"\s*:', ev[0], ev[1]),
        "pos_objects": _span(src, "_get_pos_objects"),
        "quat_objects": _span(src, "_get_quat_objects"),
        "quat_order": order,
        "metaworld_version": metaworld.__version__ if hasattr(metaworld, "__version__") else _dist_version("metaworld"),
        "reward_utils_sha": _sha256(pkg / "utils" / "reward_utils.py"),
        "xyz_env_sha": _sha256(pkg / "sawyer_xyz_env.py"),
    }


def _dist_version(name: str) -> str:
    from importlib.metadata import version
    return version(name)


