def _measure(task: str) -> Dict[str, Any]:
    """Reset every one of the 50 pinned instances exactly as `MetaWorld._reset` does
    (`MT1(task, seed=0)`, `set_task`, unseeded `reset()`) and record what moves."""
    import metaworld

    bench = metaworld.MT1(task, seed=0)
    env = bench.train_classes[task]()
    rows = []
    for inst in bench.train_tasks:
        env.set_task(inst)
        obs, _ = env.reset()
        rows.append(np.asarray(obs, dtype=float).copy())
    S = np.stack(rows)
    moving = [i for i in range(S.shape[1]) if np.ptp(S[:, i]) > 1e-6]   # the test's constants tolerance
    lo, hi = S.min(axis=0), S.max(axis=0)
    # `derived`: the goal is a rigid offset of the object draw on every instance.
    goal_minus_obj = S[:, 36:39] - S[:, 4:7]
    derived = bool(np.all(np.ptp(goal_minus_obj, axis=0) < 1e-6)) and any(
        i in moving for i in (36, 37, 38))
    return {
        "n_instances": int(len(bench.train_tasks)),
        "moving": moving, "lo": lo, "hi": hi, "hand": S[0, 0:4],
        "goal_offset": goal_minus_obj[0] if derived else None,
        "obj2_zero": bool(np.all(np.abs(S[:, 11:18]) < 1e-12)),
        "quat_zero": bool(np.all(np.abs(S[:, 7:11]) < 1e-12)),
    }


